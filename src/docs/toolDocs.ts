import { CATALOG, PROFILE_NAMES } from "../tools/catalog.js";
import type { ToolDefinition } from "../tools/types.js";

/**
 * docs/TOOLS.md is generated from the tools themselves, so it cannot drift from the code.
 * Regenerate with `npm run docs:tools`; a test fails when the committed file is out of date.
 */

interface Property {
  type?: string;
  enum?: string[];
  description?: string;
  items?: { type?: string; enum?: string[] };
}

const oneLine = (text: string) => text.replace(/\s+/g, " ").trim();
const firstSentence = (text: string) => {
  const flat = oneLine(text);
  const end = flat.search(/[.!?](\s|$)/);
  return end > 0 ? flat.slice(0, end + 1) : flat;
};
const cell = (text: string) => oneLine(text).replace(/\|/g, "\\|");

function typeOf(p: Property): string {
  if (p.enum) return p.enum.map((v) => `\`${v}\``).join(" \\| ");
  if (p.type === "array")
    return `list of ${p.items?.enum ? p.items.enum.map((v) => `\`${v}\``).join(" \\| ") : (p.items?.type ?? "values")}`;
  return p.type ?? "any";
}

export function renderToolDocs(tools: ToolDefinition[]): string {
  const known = tools.filter((t) => CATALOG[t.name]);
  const out: string[] = [
    "# Tool reference",
    "",
    "<!-- Generated by `npm run docs:tools` from the code. Do not edit by hand. -->",
    "",
    `${known.length} tools. Every result is \`{ provenance, data }\` (see the README). Choose what is advertised with`,
    "`SCMCP_PROFILES`; `sc_data_status` is always included.",
    "",
    "| Profile | Tools | Purpose |",
    "| --- | --- | --- |",
    ...PROFILE_NAMES.map((p) => {
      const names = known
        .filter((t) => CATALOG[t.name].profiles.includes(p))
        .map((t) => `\`${t.name}\``);
      const purpose = {
        core: "Everyday copilot: status, ships, trading basics, missions, patch notes, your fleet",
        trade: "The full UEX market toolbox",
        data: "Reference data, crafting, mining, patch history, wiki browsing",
        local: "Things on your PC: game log, fleet editing, your own data files",
      }[p];
      return `| **${p}** (${names.length}) | ${names.join(", ")} | ${purpose} |`;
    }),
    "",
    "## Index",
    "",
    "| Tool | Profiles | Source | Kind | Trust | What it does |",
    "| --- | --- | --- | --- | --- | --- |",
    ...known.map((t) => {
      const c = CATALOG[t.name];
      return `| [\`${t.name}\`](#${t.name}) | ${c.profiles.join(", ")} | ${cell(c.source)} | ${c.kind} | ${c.trust} | ${cell(firstSentence(t.description))} |`;
    }),
    "",
    "`trust: untrusted_text` means the answer contains text written by players or website editors: it is cleaned,",
    "shortened and must be read as data, never as instructions.",
    "",
    "## Details",
  ];

  for (const t of known) {
    const c = CATALOG[t.name];
    out.push("", `### ${t.name}`, "", oneLine(t.description), "");
    out.push(
      `*Source:* ${c.source} · *Kind:* ${c.kind} · *Trust:* ${c.trust} · *Profiles:* ${c.profiles.join(", ")}`,
      "",
    );
    const props = Object.entries(t.inputSchema.properties) as [string, Property][];
    if (props.length === 0) {
      out.push("No parameters.");
      continue;
    }
    const required = new Set(t.inputSchema.required ?? []);
    out.push("| Parameter | Type | Required | Description |", "| --- | --- | --- | --- |");
    for (const [name, p] of props) {
      out.push(
        `| \`${name}\` | ${typeOf(p)} | ${required.has(name) ? "yes" : "no"} | ${cell(p.description ?? "")} |`,
      );
    }
  }
  return `${out.join("\n")}\n`;
}
